import { existsSync, readdirSync, readFileSync } from "node:fs";
import { posix } from "node:path";

/**
 * Checks the direction of imports between the layers of `src/`, so code cannot quietly depend on a
 * layer it does not belong to:
 *
 * - `shared/` is what both processes use, so it knows neither of them.
 * - `lib/` and `components/` are shared by features; a feature may use them, never the other way.
 * - two features are independent of each other.
 * - `windows/` composes features; a feature never imports a window.
 * - a package and a plugin are leaves: the app may use them, they never use the app or each other.
 * - the renderer never imports the main process or the preload, and the main process never imports
 *   the UI.
 *
 * Run by `pnpm run lint`, so a misplaced import fails before it reaches a release. A test may
 * import the integration it checks, so test files are left alone.
 */

const SOURCE = "src";
const PACKAGES = "../../packages";
const PLUGINS = "../../plugins";

/** Generated by Panda; its imports are not ours to police. */
const IGNORED = ["src/renderer/styled-system", "../../packages/ui/src/styled-system"];

const TEST_FILE = /\.test\.tsx?$/;

/**
 * An import with the specifier in one of the three forms the project uses: `from "…"` (values,
 * types, re-exports), `import("…")` and the side-effect `import "…"`.
 */
const IMPORT =
  /\bfrom\s+["']([^"']+)["']|\bimport\s*\(\s*["']([^"']+)["']\s*\)|\bimport\s+["']([^"']+)["']/g;

type Layer =
  | { kind: "shared" }
  | { kind: "package"; name: string }
  | { kind: "plugin"; name: string }
  | { kind: "feature"; name: string }
  | { kind: "lib" }
  | { kind: "components" }
  | { kind: "windows" }
  | { kind: "renderer" }
  | { kind: "main" }
  | { kind: "preload" }
  | { kind: "web" }
  | { kind: "outside" };

interface Problem {
  file: string;
  line: number;
  message: string;
  specifier: string;
}

function layerOf(path: string): Layer {
  if (path.startsWith(`${PACKAGES}/`)) {
    const name = path.slice(PACKAGES.length + 1).split("/")[0];
    return { kind: "package", name: name ?? "" };
  }
  if (path.startsWith(`${PLUGINS}/`)) {
    const name = path.slice(PLUGINS.length + 1).split("/")[0];
    return { kind: "plugin", name: name ?? "" };
  }
  if (path === "src/shared" || path.startsWith("src/shared/")) return { kind: "shared" };
  if (path.startsWith("src/renderer/features/")) {
    const name = path.slice("src/renderer/features/".length).split("/")[0];
    return { kind: "feature", name: name ?? "" };
  }
  if (path.startsWith("src/renderer/lib/")) return { kind: "lib" };
  if (path.startsWith("src/renderer/components/")) return { kind: "components" };
  if (path.startsWith("src/renderer/windows/")) return { kind: "windows" };
  if (path.startsWith("src/renderer")) return { kind: "renderer" };
  if (path.startsWith("src/main/")) return { kind: "main" };
  if (path.startsWith("src/preload/")) return { kind: "preload" };
  if (path.startsWith("src/web/")) return { kind: "web" };
  return { kind: "outside" };
}

/** The name a workspace package gives itself in its manifest. */
function packageName(manifest: string): string | undefined {
  const value: unknown = JSON.parse(readFileSync(manifest, "utf8"));
  if (typeof value !== "object" || value === null || !("name" in value)) return undefined;
  return typeof value.name === "string" ? value.name : undefined;
}

/** The source directory of every workspace package, by the name it is imported with. */
function workspaceSources(): Map<string, string> {
  const sources = new Map<string, string>();
  for (const root of [PACKAGES, PLUGINS]) {
    if (!existsSync(root)) continue;
    for (const entry of readdirSync(root, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const dir = posix.join(root, entry.name);
      const name = packageName(posix.join(dir, "package.json"));
      if (name !== undefined) sources.set(name, posix.join(dir, "src"));
    }
  }
  return sources;
}

const WORKSPACE_SOURCES = workspaceSources();

/** The path under a workspace package's `src/` a specifier points at, or undefined for a builtin. */
function targetOf(file: string, specifier: string): string | undefined {
  // A `?raw` suffix asks for the file's text; the path itself is what the edge is about
  const clean = specifier.replace(/\?.*$/, "");
  if (clean.startsWith("@shared/")) {
    return posix.normalize(`src/shared/${clean.slice("@shared/".length)}`);
  }
  if (clean.startsWith("@pupitre/")) {
    const [name = "", ...rest] = clean.slice("@pupitre/".length).split("/");
    const base = WORKSPACE_SOURCES.get(`@pupitre/${name}`);
    if (base === undefined) return undefined;
    return posix.normalize([base, ...rest].join("/"));
  }
  if (clean.startsWith("@/")) return posix.normalize(`src/renderer/${clean.slice("@/".length)}`);
  if (clean.startsWith(".")) return posix.normalize(posix.join(posix.dirname(file), clean));
  return undefined;
}

/** The layers that draw the interface and run in the renderer. */
const UI = new Set<Layer["kind"]>(["renderer", "lib", "components", "feature", "windows"]);

function violation(source: Layer, target: Layer): string | undefined {
  if (target.kind === "outside") return undefined;

  // A package and a plugin are the bottom of the tree: the app may use them, never the other way
  if (source.kind === "package" && target.kind !== "package") {
    return "a package cannot import the app, its processes or a plugin";
  }
  if (
    source.kind === "plugin" &&
    target.kind !== "package" &&
    !(target.kind === "plugin" && target.name === source.name)
  ) {
    return "a plugin cannot import the app or another plugin";
  }
  if (source.kind === "shared" && target.kind !== "shared" && target.kind !== "package") {
    return "shared code cannot import a process or the UI";
  }
  if (
    (source.kind === "lib" || source.kind === "components") &&
    (target.kind === "feature" || target.kind === "windows")
  ) {
    const layer = source.kind === "lib" ? "lib" : "components";
    return `${layer} is shared by features and cannot import a feature or a window`;
  }
  if (source.kind === "feature" && target.kind === "feature" && source.name !== target.name) {
    return `feature "${source.name}" cannot import feature "${target.name}"`;
  }
  if (source.kind === "feature" && target.kind === "windows") {
    return "a feature cannot import a window";
  }
  if (
    (UI.has(source.kind) || source.kind === "web") &&
    (target.kind === "main" || target.kind === "preload")
  ) {
    return "the renderer cannot import the main process or the preload";
  }
  if (source.kind === "main" && (UI.has(target.kind) || target.kind === "web")) {
    return "the main process cannot import the UI";
  }
  if (
    source.kind === "preload" &&
    (UI.has(target.kind) || target.kind === "main" || target.kind === "web")
  ) {
    return "the preload imports only the shared contract";
  }
  return undefined;
}

function sourceFiles(dir: string, found: string[] = []): string[] {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = posix.join(dir, entry.name);
    if (IGNORED.some((ignored) => path === ignored || path.startsWith(`${ignored}/`))) continue;
    if (entry.isDirectory()) sourceFiles(path, found);
    else if (/\.tsx?$/.test(entry.name) && !TEST_FILE.test(entry.name)) found.push(path);
  }
  return found;
}

function lineOf(text: string, index: number): number {
  return text.slice(0, index).split("\n").length;
}

const files = sourceFiles(SOURCE);
for (const root of [PACKAGES, PLUGINS]) {
  if (!existsSync(root)) continue;
  for (const entry of readdirSync(root, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const dir = posix.join(root, entry.name, "src");
    if (existsSync(dir)) files.push(...sourceFiles(dir));
  }
}

const problems: Problem[] = [];
for (const file of files) {
  const text = readFileSync(file, "utf8");
  for (const match of text.matchAll(IMPORT)) {
    const specifier = match[1] ?? match[2] ?? match[3];
    if (specifier === undefined) continue;
    const target = targetOf(file, specifier);
    if (target === undefined) continue;
    const message = violation(layerOf(file), layerOf(target));
    if (message === undefined) continue;
    problems.push({ file, line: lineOf(text, match.index ?? 0), message, specifier });
  }
}

if (problems.length > 0) {
  for (const problem of problems) {
    console.error(
      `${problem.file}:${problem.line}: ${problem.message} (imports "${problem.specifier}")`,
    );
  }
  process.exit(1);
}

console.log("Import boundaries are respected.");
